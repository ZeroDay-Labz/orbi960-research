"""Ghidra headless driver.

Wraps `analyzeHeadless` for reproducible, scripted analysis of ARM ELF
binaries. The driver intentionally keeps per-binary Ghidra projects small
(one binary each), so re-running against a newer firmware version doesn't
collide with the older project.

The decompile post-script is generated on demand in the repo's research_output
directory. We never modify the user's Ghidra install.

Capabilities:
    - check(): probe for analyzeHeadless and report Ghidra version
    - import_binary(fw_key, rel_path, project=...): auto-analyze + save
    - decompile(fw_key, rel_path, [func_names], project=...): post-script that
      calls DecompInterface for each named function and writes JSON output
"""
from __future__ import annotations

import json
import os
import shlex
import shutil
from dataclasses import dataclass
from pathlib import Path

from . import config
from .common import get_logger, run

LOG = get_logger("orbi_fw.ghidra")


POST_SCRIPT_TEMPLATE = r"""// Ghidra post-script generated by orbi_fw_research.ghidra.
// Emits JSON for each requested function.
// Args passed by analyzeHeadless -postScript args: <out_json> <func_names_csv>

import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileOptions;
import ghidra.app.decompiler.DecompileResults;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;
import ghidra.program.model.symbol.SymbolIterator;
import ghidra.program.model.symbol.Symbol;

import java.io.PrintWriter;
import java.io.FileWriter;
import java.util.ArrayList;
import java.util.List;

public class OrbiDecompile extends GhidraScript {

    @Override
    protected void run() throws Exception {
        String[] args = getScriptArgs();
        if (args.length < 2) {
            printerr("usage: OrbiDecompile <out_json> <func_names_csv>");
            return;
        }
        String outPath = args[0];
        String[] names = args[1].split(",");

        DecompInterface d = new DecompInterface();
        d.setOptions(new DecompileOptions());
        d.openProgram(currentProgram);

        StringBuilder sb = new StringBuilder();
        sb.append("{\n");
        sb.append("  \"program\": \"").append(escape(currentProgram.getName())).append("\",\n");
        sb.append("  \"functions\": [\n");

        boolean first = true;
        for (String nm : names) {
            String want = nm.trim();
            if (want.isEmpty()) continue;
            Function f = findByName(want);
            if (!first) sb.append(",\n");
            first = false;
            sb.append("    {\"name\":\"").append(escape(want)).append("\"");
            if (f == null) {
                sb.append(", \"found\": false }");
                continue;
            }
            sb.append(", \"found\": true");
            sb.append(", \"entry\": \"").append(f.getEntryPoint().toString()).append("\"");
            DecompileResults res = d.decompileFunction(f, 60, monitor);
            String code = "";
            if (res != null && res.getDecompiledFunction() != null) {
                code = res.getDecompiledFunction().getC();
            }
            sb.append(", \"c\": \"").append(escape(code)).append("\"");
            sb.append("}");
        }
        sb.append("\n  ]\n}\n");

        PrintWriter pw = new PrintWriter(new FileWriter(outPath));
        pw.write(sb.toString());
        pw.close();
        println("wrote " + outPath);
    }

    private Function findByName(String name) {
        FunctionIterator it = currentProgram.getFunctionManager().getFunctions(true);
        while (it.hasNext()) {
            Function f = it.next();
            if (f.getName().equals(name)) return f;
        }
        SymbolIterator si = currentProgram.getSymbolTable().getSymbolIterator(name, true);
        while (si.hasNext()) {
            Symbol s = si.next();
            Function f = getFunctionAt(s.getAddress());
            if (f != null) return f;
        }
        return null;
    }

    private String escape(String s) {
        if (s == null) return "";
        StringBuilder r = new StringBuilder(s.length() + 16);
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '\\' || c == '"') { r.append('\\').append(c); }
            else if (c == '\n') r.append("\\n");
            else if (c == '\r') r.append("\\r");
            else if (c == '\t') r.append("\\t");
            else if (c < 0x20) r.append(String.format("\\u%04x", (int) c));
            else r.append(c);
        }
        return r.toString();
    }
}
"""


LANGUAGE_ARM_LE_V7_DEFAULT = "ARM:LE:32:v7"


@dataclass
class GhidraDriver:
    install_dir: Path | None = None
    projects_dir: Path | None = None
    scripts_dir: Path | None = None

    def __post_init__(self) -> None:
        if self.install_dir is None:
            self.install_dir = config.resolve_ghidra()
        if self.projects_dir is None:
            self.projects_dir = config.RESEARCH_OUTPUT_DIR / "ghidra" / "projects"
        if self.scripts_dir is None:
            self.scripts_dir = config.RESEARCH_OUTPUT_DIR / "ghidra" / "scripts"
        self.projects_dir.mkdir(parents=True, exist_ok=True)
        self.scripts_dir.mkdir(parents=True, exist_ok=True)

    @property
    def headless(self) -> Path | None:
        if self.install_dir is None:
            return None
        return self.install_dir / "support" / "analyzeHeadless"

    def check(self) -> dict:
        info = {
            "install_dir": str(self.install_dir) if self.install_dir else None,
            "headless": str(self.headless) if self.headless else None,
            "available": False,
            "version": "",
        }
        if self.headless is None or not self.headless.is_file():
            return info
        info["available"] = True
        ver_file = (self.install_dir or Path()) / "Ghidra" / "application.properties"
        if ver_file.is_file():
            for line in ver_file.read_text(errors="replace").splitlines():
                if line.startswith("application.version="):
                    info["version"] = line.split("=", 1)[1].strip()
                    break
        return info

    def _ensure_post_script(self) -> Path:
        p = self.scripts_dir / "OrbiDecompile.java"
        if not p.is_file() or p.read_text() != POST_SCRIPT_TEMPLATE:
            p.write_text(POST_SCRIPT_TEMPLATE)
        return p

    def _project_name(self, project: str) -> tuple[Path, str]:
        return self.projects_dir, project

    def _program_name(self, fw_key: str, binary_path: str) -> str:
        # Keep program name unique per firmware key.
        base = Path(binary_path).name
        return f"{fw_key}__{base}"

    def _binary_abs(self, fw_key: str, binary_path: str) -> Path:
        if fw_key not in config.FIRMWARE_KEYS:
            raise KeyError(fw_key)
        key = config.FIRMWARE_KEYS[fw_key]
        p = key.rootfs / binary_path.lstrip("/")
        if not p.is_file():
            raise FileNotFoundError(p)
        return p

    def import_binary(self, fw_key: str, binary_path: str, *,
                      project: str = "orbi_research", lang: str = LANGUAGE_ARM_LE_V7_DEFAULT,
                      overwrite: bool = False) -> dict:
        if self.headless is None:
            raise RuntimeError("Ghidra not found; set GHIDRA_INSTALL_DIR or install Ghidra")
        bin_abs = self._binary_abs(fw_key, binary_path)
        proj_dir, proj_name = self._project_name(project)
        program_name = self._program_name(fw_key, binary_path)
        args = [
            str(self.headless), str(proj_dir), proj_name,
            "-import", str(bin_abs),
            "-processor", lang,
            "-recursive", "-analysisTimeoutPerFile", "600",
            "-scriptPath", str(self.scripts_dir),
            "-postScript", "AnalyzeHeadlessPrescript.java",  # no-op if missing
        ]
        if overwrite:
            args.append("-overwrite")
        LOG.info("ghidra import: %s", " ".join(shlex.quote(a) for a in args))
        r = run(args, timeout=1200)
        return {"rc": r.rc, "stdout_tail": r.stdout[-2000:], "stderr_tail": r.stderr[-1000:]}

    def decompile(self, fw_key: str, binary_path: str, functions: list[str], *,
                  project: str = "orbi_research") -> dict:
        if self.headless is None:
            raise RuntimeError("Ghidra not found; set GHIDRA_INSTALL_DIR or install Ghidra")
        script_path = self._ensure_post_script()
        proj_dir, proj_name = self._project_name(project)
        program_name = self._program_name(fw_key, binary_path)
        out_json = (config.RESEARCH_OUTPUT_DIR / "ghidra" / "decompile" /
                    fw_key / f"{Path(binary_path).name}.json")
        out_json.parent.mkdir(parents=True, exist_ok=True)
        args = [
            str(self.headless), str(proj_dir), proj_name,
            "-process", program_name,
            "-noanalysis",
            "-scriptPath", str(self.scripts_dir),
            "-postScript", "OrbiDecompile.java",
            str(out_json), ",".join(functions),
        ]
        LOG.info("ghidra decompile: %s", " ".join(shlex.quote(a) for a in args))
        r = run(args, timeout=600)
        decoded: dict = {}
        if out_json.is_file():
            try:
                decoded = json.loads(out_json.read_text(encoding="utf-8"))
            except Exception as e:
                decoded = {"error": f"json parse failed: {e}"}
        return {
            "rc": r.rc,
            "output_file": str(out_json),
            "stdout_tail": r.stdout[-1000:],
            "stderr_tail": r.stderr[-500:],
            "result": decoded,
        }
